# -*- coding: utf-8 -*-
"""
生成 shandong-fiscal/data.js。

原始数据来源：山东省统计局、山东省财政厅公开数据，
经中诚信国际在山东各市城投债跟踪评级报告（2024—2026 年度）中整理的
「山东省下属地市经济财政概况」表（2023 / 2024 / 2025 三个年度）。
三年口径一致，均为现价、亿元。

字段：
  gdp  —— 地区生产总值，亿元
  rev  —— 一般公共预算收入，亿元
  pc   —— 2025 年人均 GDP，万元（全省口径由省统计局公布，个别市按 2024 年末
          常住人口测算，见 notes）

用法：
  python scripts/build_shandong_data.py
输出：
  shandong-fiscal/data.js
"""

import json
import os

YEARS = [2023, 2024, 2025]

# 三大经济圈（2020 年山东省确定的官方划分，5 + 7 + 4 = 16，无遗漏无重叠）
CIRCLE = {
    "青岛": "胶东", "烟台": "胶东", "潍坊": "胶东", "威海": "胶东", "日照": "胶东",
    "济南": "省会", "淄博": "省会", "泰安": "省会", "聊城": "省会",
    "德州": "省会", "滨州": "省会", "东营": "省会",
    "临沂": "鲁南", "枣庄": "鲁南", "济宁": "鲁南", "菏泽": "鲁南",
}

# name, gdp(2023,2024,2025), rev(2023,2024,2025), 人均GDP 2025(万元)
ROWS = [
    ("青岛市", (15760.34, 16719.46, 17560.67), (1337.80, 1339.26, 1340.72), 16.70),
    ("济南市", (12757.40, 13527.60, 14210.00), (1060.80, 1083.05, 1093.35), 14.78),
    ("烟台市", (10162.46, 10782.83, 11350.98), (673.87, 698.81, 700.08), 16.21),
    ("潍坊市", (7606.00, 8203.21, 8587.36), (608.32, 619.56, 630.52), 9.26),
    ("临沂市", (6105.20, 6555.80, 6862.20), (445.25, 468.51, 482.57), 6.38),
    ("济宁市", (5516.47, 5867.50, 6128.10), (475.01, 496.26, 502.72), 7.54),
    ("淄博市", (4561.79, 4884.08, 5088.89), (395.30, 411.44, 419.73), 11.05),
    ("菏泽市", (4464.49, 4802.58, 4937.40), (316.51, 329.18, 333.37), 5.80),
    ("东营市", (3899.06, 4307.70, 4502.73), (284.63, 302.15, 313.30), 20.37),
    ("德州市", (3805.27, 4047.73, 4214.61), (250.60, 263.36, 271.24), 7.77),
    ("威海市", (3513.54, 3728.62, 3896.09), (237.38, 249.75, 257.91), 13.38),
    ("泰安市", (3323.86, 3622.10, 3803.50), (239.24, 252.69, 261.96), 7.27),
    ("滨州市", (3118.85, 3404.74, 3558.17), (292.14, 306.92, 318.26), 9.25),
    ("聊城市", (2926.36, 3167.96, 3304.15), (244.62, 257.10, 264.80), 5.74),
    ("日照市", (2390.86, 2556.89, 2689.96), (195.34, 204.16, 210.26), 9.24),
    ("枣庄市", (2156.74, 2386.41, 2502.52), (181.05, 191.58, 200.20), 6.58),
]

PROVINCE = {
    "gdp": (92068.70, 98566.00, 103197.50),
    "rev": (7464.70, 7711.50, 7864.26),
    "pc": 10.28,
}


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(os.path.dirname(here), "shandong-fiscal", "data.js")

    cities = []
    for name, gdp, rev, pc in ROWS:
        short = name.replace("市", "")
        cities.append({
            "id": short,
            "zh": name,
            "circle": CIRCLE[short],
            "gdp": list(gdp),
            "rev": list(rev),
            "pc": pc,
        })

    payload = {
        "years": YEARS,
        "asOf": "2025 年年度数据",
        "province": {"zh": "山东省", "gdp": list(PROVINCE["gdp"]),
                     "rev": list(PROVINCE["rev"]), "pc": PROVINCE["pc"]},
        "cities": cities,
        "notes": [
            "各市数据为现价、亿元。GDP 与一般公共预算收入均为年度决算口径。",
            "人均 GDP 按 2025 年地区生产总值除以常住人口计算；菏泽市、临沂市 2025 年末常住人口尚未公布，采用 2024 年末数，两市人均值略偏低。",
            "16 市加总与全省数不完全相等，差额来自省级不可分摊的部分及统计调整，属正常口径差异，本页不强行配平。",
        ],
    }

    body = json.dumps(payload, ensure_ascii=False, indent=2)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* 由 scripts/build_shandong_data.py 生成，请勿手工编辑。 */\n")
        f.write("window.SD = " + body + ";\n")

    # ---- 校验 ----
    print("写入：" + out)
    for i, y in enumerate(YEARS):
        g = sum(c["gdp"][i] for c in cities)
        r = sum(c["rev"][i] for c in cities)
        pg, pr = PROVINCE["gdp"][i], PROVINCE["rev"][i]
        print(f"{y}  GDP 16市合计 {g:10.2f}  全省 {pg:10.2f}  差 {g - pg:+7.2f} ({(g / pg - 1) * 100:+.2f}%)")
        print(f"{y}  财政16市合计 {r:10.2f}  全省 {pr:10.2f}  差 {r - pr:+7.2f} ({(r / pr - 1) * 100:+.2f}%)")

    print("\n财政负担率（2025，一般公共预算收入 / GDP）：")
    rows = sorted(((c["rev"][2] / c["gdp"][2] * 100, c["zh"]) for c in cities), reverse=True)
    for v, n in rows:
        print(f"  {n}  {v:.2f}%")
    print(f"  全省        {PROVINCE['rev'][2] / PROVINCE['gdp'][2] * 100:.2f}%")

    print("\n名义增速 2023 → 2025：")
    for c in cities:
        print(f"  {c['zh']}  GDP {(c['gdp'][2] / c['gdp'][0] - 1) * 100:+6.2f}%   "
              f"财政 {(c['rev'][2] / c['rev'][0] - 1) * 100:+6.2f}%")
    print(f"  全省    GDP {(PROVINCE['gdp'][2] / PROVINCE['gdp'][0] - 1) * 100:+.2f}%   "
          f"财政 {(PROVINCE['rev'][2] / PROVINCE['rev'][0] - 1) * 100:+.2f}%")


if __name__ == "__main__":
    main()
